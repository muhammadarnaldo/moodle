/** The fields needed to render an item from the existing recent-items service. */
export interface RecentItemData {
    /** Identifier of the recent access record. */
    id: number;
    /** Activity name, formatted and cleaned by the server exporter. */
    name: string;
    /** Course name, formatted and cleaned by the server exporter. */
    coursename: string;
    /** Activity URL generated by the server. */
    viewurl: string;
    /** Activity icon HTML rendered by Moodle, including plugin icons. */
    icon: string;
}
